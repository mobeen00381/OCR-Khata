function item(
  id: string,
  transactionId: string,
  productId: string,
  rawName: string,
  quantity: number,
  unit: TransactionItem["unit"],
  rate: number,
): TransactionItem {
  return {
    id,
    transaction_id: transactionId,
    product_id: productId,
    raw_scanned_name: rawName,
    quantity,
    unit,
    rate,
    amount: quantity * rate,
  };
}

